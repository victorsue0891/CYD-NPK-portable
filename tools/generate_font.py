"""Generate the small OFL Chinese glyph set used by the firmware (Pillow required).

The generated header is checked in; normal firmware builds do not need Python/fonts.
"""
from pathlib import Path
import re
import urllib.request
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'assets/fonts/NotoSansCJKtc-Regular.otf'
URL = 'https://raw.githubusercontent.com/notofonts/noto-cjk/main/Sans/OTF/TraditionalChinese/NotoSansCJKtc-Regular.otf'

def main():
    if not FONT.exists():
        FONT.parent.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(URL, FONT)
    font = ImageFont.truetype(str(FONT), 18)
    strings = re.findall(r'"([^"]*)"', (ROOT / 'include/UiText.h').read_text(encoding='utf-8'))
    chars = sorted({c for s in strings for c in s if ord(c) > 127})
    lines = ['// Generated by tools/generate_font.py; glyphs derived from Noto Sans CJK TC.',
             '// Copyright 2014-2021 Adobe (http://www.adobe.com/). SIL OFL 1.1: assets/fonts/OFL.txt',
             '#pragma once', '#include <stdint.h>', '#include <pgmspace.h>',
             'struct ChineseGlyph { uint32_t code; uint8_t bits[54]; };',
             'static const ChineseGlyph chineseGlyphs[] PROGMEM = {']
    for c in chars:
        im = Image.new('L', (18, 18))
        # Anchor the actual visible bounds, preserving the full 18px glyph.
        box = font.getbbox(c)
        ImageDraw.Draw(im).text((0, -box[1]), c, font=font, fill=255)
        data = []
        for y in range(18):
            for bx in range(3):
                b = 0
                for bit in range(8):
                    x = bx * 8 + bit
                    if x < 18 and im.getpixel((x, y)) >= 96:
                        b |= 0x80 >> bit
                data.append(b)
        lines.append('    {0x%04X, {%s}}, // %s' % (ord(c), ','.join('0x%02X' % b for b in data), c))
    lines.append('};')
    (ROOT / 'include/ChineseFont.h').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'Generated {len(chars)} glyphs, {len(chars)*54} bitmap bytes')

if __name__ == '__main__':
    main()
